let a = 10, b = 3;
console.log(a + b); // 13
console.log(a - b); // 7
console.log(a * b); // 30
console.log(a / b); // 3.3333333333333335
console.log(a % b); // 1 (remainder / modulus)
console.log(a ** b); // 1000 (10 to the power 3)
